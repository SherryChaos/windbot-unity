# -*- coding: utf-8 -*-
"""Generate Unity/WindBotResources.g.cs from Decks/*.ydk and Dialogs/*.json."""
import io, os

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
out = os.path.join(root, 'Unity', 'WindBotResources.g.cs')

def read(path):
    with io.open(path, 'r', encoding='utf-8-sig') as f:
        return f.read().replace('\r\n', '\n').replace('\r', '\n')

entries = []
for folder in ('Decks', 'Dialogs'):
    base = os.path.join(root, folder)
    for name in sorted(os.listdir(base)):
        if not (name.endswith('.ydk') or name.endswith('.json')):
            continue
        entries.append((folder + '/' + name, read(os.path.join(base, name))))

with io.open(out, 'w', encoding='utf-8', newline='\n') as f:
    f.write('// <auto-generated> by Tools/gen_windbot_resources.py - do not edit by hand. </auto-generated>\n')
    f.write('using System.Collections.Generic;\n\n')
    f.write('namespace WindBot.Unity\n{\n')
    f.write('    public static class WindBotResources\n    {\n')
    f.write('        private static readonly Dictionary<string, string> Map = new Dictionary<string, string>\n        {\n')
    for key, text in entries:
        f.write('            { "' + key + '", @"' + text.replace('"', '""') + '" },\n')
    f.write('        };\n\n')
    f.write('        public static IEnumerable<KeyValuePair<string, string>> All { get { return Map; } }\n\n')
    f.write('        public static string Get(string directory, string filename, string extension)\n        {\n')
    f.write('            string value;\n')
    f.write('            if (Map.TryGetValue(directory + "/" + filename + "." + extension, out value))\n                return value;\n')
    f.write('            if (Map.TryGetValue(directory + "/" + filename, out value))\n                return value;\n')
    f.write('            return null;\n')
    f.write('        }\n')
    f.write('    }\n}\n')

print('wrote', out, len(entries), 'entries')
